def dir_size_mb(path):
    total = 0
    for root, _dirs, files in os.walk(path):
        for f in files:
            fp = os.path.join(root, f)
            if os.path.isfile(fp):
                total += os.path.getsize(fp)
    return total / (1024 * 1024)


def _copy_ignore(dirpath, names):
    """حذف بایت‌کد/فایل سیستمی + آپلودهای ماشین توسعه (حریم خصوصی!)."""
    ignored = set()
    for name in names:
        if name in ("__pycache__", ".DS_Store", "Thumbs.db"):
            ignored.add(name)
        elif name.endswith((".pyc", ".pyo")):
            ignored.add(name)
    # static/uploads فقط ساختارش روی هاست لازم است، نه فایل‌هایش
    if os.path.basename(dirpath) == "static" and "uploads" in names:
        ignored.add("uploads")
    return ignored


def _repo_root_modules():
    """ماژول‌های سطح‌ریشه‌ی ریپو (foo.py → foo) — برای راستی‌آزمایی importها."""
    found = set()
    for name in os.listdir(ROOT):
        if name.endswith(".py") and os.path.isfile(os.path.join(ROOT, name)):
            found.add(name[:-3])
    return found


def _verify_staged_imports(stage):
    """آیا کدی در بسته به ماژول ریشه‌ای اشاره می‌کند که بسته‌بندی نشده؟

    قبلاً فقط importهای app.py چک می‌شد؛ حالا همه‌ی فایل‌های routes/models/
    utils/bootstrap هم اسکن می‌شوند تا روی هاست ModuleNotFoundError نگیریم.
    خروجی: فهرست مشکل‌ها (خالی = سالم).
    """
    repo_modules = _repo_root_modules()
    staged = set()
    for name in os.listdir(stage):
        if name.endswith(".py") and os.path.isfile(os.path.join(stage, name)):
            staged.add(name[:-3])
    staged_packages = {d for d in DIRS if os.path.isdir(os.path.join(stage, d))}

    problems = []
    for root, _dirs, files in os.walk(stage):
        for name in files:
            if not name.endswith(".py"):
                continue
            path = os.path.join(root, name)
            try:
                with open(path, encoding="utf-8") as handle:
                    tree = ast.parse(handle.read())
            except (OSError, SyntaxError):
                continue
            imported = set()
            for node in ast.walk(tree):
                if isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
                    imported.add(node.module.split(".")[0])
                elif isinstance(node, ast.Import):
                    for alias in node.names:
                        imported.add(alias.name.split(".")[0])
            for mod in sorted(imported):
                if mod in repo_modules and mod not in staged \
                        and mod not in staged_packages:
                    rel = os.path.relpath(path, stage).replace(os.sep, "/")
                    problems.append(f"{rel} به «{mod}.py» نیاز دارد ولی در بسته نیست")
    return problems


