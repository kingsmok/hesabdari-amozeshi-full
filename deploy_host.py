def _prepare_console():
    if os.name != "nt":
        return
    for stream in (sys.stdout, sys.stderr):
        try:
            if getattr(stream, "isatty", lambda: False)():
                continue
            stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass


