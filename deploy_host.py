def main():
    os.chdir(ROOT)
    _prepare_console()

    for f in ("app.py", "requirements.txt", "VERSION", "passenger_wsgi.py"):
        if not os.path.exists(f):
            die(
                f"فایل {f} پیدا نشد.\n"
                "  این فایل باید از پوشه‌ی اصلی پروژه اجرا شود."
            )

    version = open("VERSION", encoding="utf-8").read().strip() or "1.0.0"
    admin_user, admin_pass = _default_credentials()

    header()
    started = time.time()

    # ── [1/5] پاک‌سازی پوشه‌ی قبلی ──
    step(1, 5, "آماده‌سازی پوشه‌ی host_deploy ...")
    if os.path.exists(STAGE):
        shutil.rmtree(STAGE)
        print("      پوشه‌ی قبلی پاک شد")
    os.makedirs(STAGE)
    print("      OK")

    # ── [2/5] کپی فایل‌ها ──
    step(2, 5, "کپی فایل‌های مورد نیاز ...")
    count = 0

    # فایل‌های ریشه
    for f in REQUIRED_FILES:
        if not os.path.exists(f):
            die(f"فایل {f} در پروژه پیدا نشد — کپی متوقف شد")
        shutil.copy2(f, os.path.join(STAGE, f))
        count += 1
        print(f"      ✓ {f}")

    for f in OPTIONAL_FILES:
        if os.path.exists(f):
            shutil.copy2(f, os.path.join(STAGE, f))
            count += 1
            print(f"      ✓ {f}")

    if os.path.exists(os.path.join(ROOT, "settings.json")):
        print("      ○ settings.json محلی کپی نشد (حاوی راز/مسیر محلی است) — "
              "نسخه‌ی تمیز هاست ساخته می‌شود")

    # پوشه‌ها
    for d in DIRS:
        if not os.path.isdir(d):
            die(f"پوشه‌ی {d} در پروژه پیدا نشد — کپی متوقف شد")
        shutil.copytree(d, os.path.join(STAGE, d), ignore=_copy_ignore)
        n = sum(len(fs) for _r, _ds, fs in os.walk(os.path.join(STAGE, d)))
        count += n
        print(f"      ✓ {d}/  ({n} فایل)")

    print("      ✓ static/uploads/ انتقال نیافت (حریم خصوصی) — ساختار خالی ساخته می‌شود")

    # ── [3/5] فایل‌های مخصوص هاست ──
    step(3, 5, "ساخت settings.json و پوشه‌های runtime ...")

    for d in RUNTIME_DIRS:
        full = os.path.join(STAGE, d)
        os.makedirs(full, exist_ok=True)
        # نگه‌داشتن پوشه‌ی خالی در ZIP + جلوگیری از directory listing
        with open(os.path.join(full, ".gitkeep"), "w", encoding="utf-8") as handle:
            handle.write("")
    print("      ✓ پوشه‌های instance/ و backups/ و logs/ و زیرمجلدهای آپلود ساخته شدند")

    # سد دفاعی داخل پوشه‌های داده (در برابر سرو مستقیم توسط Apache)
    for d in ("instance", "backups", "logs"):
        with open(os.path.join(STAGE, d, ".htaccess"), "w", encoding="utf-8") as handle:
            handle.write(DENY_ALL_HTACCESS)
    with open(os.path.join(STAGE, "static", "uploads", ".htaccess"),
              "w", encoding="utf-8") as handle:
        handle.write(UPLOADS_HTACCESS)
    print("      ✓ فایل‌های محافظ .htaccess داخل پوشه‌های داده گذاشته شد")

    # settings.json تمیز مخصوص هاست (بدون هیچ رازی)
    with open(os.path.join(STAGE, "settings.json"), "w", encoding="utf-8") as handle:
        json.dump(HOST_SETTINGS, handle, indent=2, ensure_ascii=False)
    print("      ✓ settings.json تمیز هاست ساخته شد (SQLite پیش‌فرض، بدون کلید)")
    print(f"      مجموعاً {count} فایل")

    # ── [4/5] بررسی نهایی ──
    step(4, 5, "بررسی پوشه‌ی خروجی ...")
    problems = []
    for f in ("app.py", "requirements.txt", "requirements-prod.txt",
              "gunicorn.conf.py", "passenger_wsgi.py", "wsgi.py",
              ".htaccess", "settings.json"):
        if not os.path.exists(os.path.join(STAGE, f)):
            problems.append(f)
    for needed in ("startup_checks.py", "passenger_wsgi.py", "wsgi.py"):
        if not os.path.exists(os.path.join(STAGE, needed)):
            problems.append(f"{needed} (برای هاست Python 3.11 لازم است)")

    # entry point باید شیء application را صادر کند
    try:
        passenger_src = open(os.path.join(STAGE, "passenger_wsgi.py"),
                             encoding="utf-8").read()
        if "application" not in passenger_src:
            problems.append("passenger_wsgi.py شیء application را صادر نمی‌کند!")
        if "ACADEMY_DISABLE_SCHEDULER" not in passenger_src:
            problems.append("passenger_wsgi.py زمان‌بند را روی هاست اشتراکی خاموش نمی‌کند!")
    except OSError as exc:
        problems.append(f"passenger_wsgi.py خوانده نشد: {exc}")

    # ‎.htaccess نباید ریدایرکت قدیمیِ خراب‌کننده‌ی Passenger را داشته باشد
    try:
        htaccess = open(os.path.join(STAGE, ".htaccess"), encoding="utf-8").read()
        if "wsgi.py/$1" in htaccess or "wsgi.py/" in htaccess:
            problems.append(".htaccess هنوز RewriteRule خراب به wsgi.py دارد (Passenger را می‌شکند)!")
    except OSError as exc:
        problems.append(f".htaccess خوانده نشد: {exc}")

    # وابستگی‌های حیاتی باید در requirements باشند
    try:
        requirements = open(os.path.join(STAGE, "requirements.txt"),
                            encoding="utf-8").read()
        for package in ("Flask==", "Flask-SQLAlchemy", "SQLAlchemy==",
                        "Flask-Login", "PyMySQL"):
            if package not in requirements:
                problems.append(f"requirements.txt بسته‌ی {package} را ندارد!")
    except OSError as exc:
        problems.append(f"requirements.txt خوانده نشد: {exc}")

    # همه‌ی importهای محلی باید در بسته باشند (نه فقط app.py)
    problems.extend(_verify_staged_imports(STAGE))

    for banned in ("academy.db", "cookies.txt", "config.ini", "app_desktop.py",
                   "host_deploy_v", ".git"):
        if os.path.exists(os.path.join(STAGE, banned)):
            problems.append(f"{banned} (نمی‌بایست در خروجی باشد!)")
    # دیتابیس/رازِ نشت‌کرده در هر عمقی ممنوع
    for root, _dirs, files in os.walk(STAGE):
        for name in files:
            if name.endswith((".db", ".db-wal", ".db-shm", ".db-journal",
                              ".sqlite", ".sqlite3")) or name == "cookies.txt":
                problems.append(os.path.relpath(os.path.join(root, name), STAGE)
                                + " (فایل داده/راز نباید در بسته باشد!)")
    if problems:
        die("مشکلی در پوشه‌ی خروجی پیدا شد:\n  • " + "\n  • ".join(problems[:15]))
    size_mb = dir_size_mb(STAGE)
    print(f"      OK - پوشه آماده است ({size_mb:.1f} MB)")
    print("      OK - همه‌ی importهای محلی در بسته هستند")

    # ── [5/5] ساخت ZIP ──
    step(5, 5, "ساخت فایل ZIP برای آپلود ...")
    zip_name = f"host_deploy_v{version}.zip"
    zip_path = os.path.join(ROOT, zip_name)
    if os.path.exists(zip_path):
        os.remove(zip_path)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for root, dirs, files in os.walk(STAGE):
            dirs[:] = [d for d in dirs if d not in NEVER_COPY]
            # پوشه‌های خالی را هم در ZIP نگه می‌داریم
            rel = os.path.relpath(root, ROOT)
            if not files and not [d for d in dirs if d not in NEVER_COPY]:
                zf.writestr(rel.replace(os.sep, "/") + "/", "")
            for f in files:
                fp = os.path.join(root, f)
                arc = os.path.relpath(fp, ROOT).replace(os.sep, "/")
                zf.write(fp, arc)
    zmb = os.path.getsize(zip_path) / (1024 * 1024)
    print(f"      OK: {zip_name}  ({zmb:.1f} MB)")

    # ── راهنمای آپلود ──
    total = time.time() - started
    print()
    print("  ╔" + "═" * 58 + "╗")
    print("  ║  ✅ فایل‌ها آماده‌ی آپلود هستند!                          ║")
    print("  ╚" + "═" * 58 + "╝")
    print()
    print(f"  • پوشه‌ی آماده:      {os.path.abspath(STAGE)}")
    print(f"  • فایل ZIP برای آپلود: {os.path.abspath(zip_path)}")
    print()
    print("  راهنمای آپلود (cPanel با Python 3.11):")
    print("  ─────────────────────────────────────────────────────────")
    print("  ۱. فایل ZIP را در File Manager داخل public_html آپلود و Extract کنید")
    print("     (تیک Delete archive after extraction را بزنید؛ پوشه‌ی host_deploy ساخته می‌شود)")
    print("  ۲. در cPanel وارد Setup Python App شوید و یک اپلیکیشن بسازید:")
    print("       • Python version:            3.11")
    print("       • Application root:          public_html/host_deploy")
    print("       • Application startup file:  passenger_wsgi.py")
    print("       • Application Entry point:   application")
    print("  ۳. نصب پکیج‌ها — اگر SSH/Terminal ندارید، فقط با دکمه‌ی Run Pip Install:")
    print("       • Setup Python App → اپلیکیشن → Configuration files")
    print("       • `requirements-nobuild.txt` را Add کنید (از قبل در بسته است)")
    print("       • دکمه‌ی Run Pip Install را بزنید و همین فایل را انتخاب کنید")
    print("     (این فایل `--only-binary=:all:` دارد؛ پس greenlet هرگز از سورس")
    print("     کامپایل نمی‌شود و خطای `Failed building wheel for greenlet` نمی‌دهد)")
    print("     اگر Terminal دارید، به‌جای آن می‌توانید:")
    print("       pip install --prefer-binary -r requirements.txt")
    print("     یا برای حل خودکار خطای greenlet:")
    print("       python tools/install_deps.py")
    print("  ۴. مطمئن شوید پوشه‌های instance/ و backups/ و logs/ و static/uploads/")
    print("     قابل نوشتن‌اند (در Terminal همان اپلیکیشن):")
    print("       chmod 755 instance backups logs static/uploads")
    print("  ۵. اپلیکیشن را Restart کنید و دامنه را باز کنید؛ ورود پیش‌فرض:")
